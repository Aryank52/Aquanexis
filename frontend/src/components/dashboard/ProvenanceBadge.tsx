import { cn } from '@utils/cn';
import { Database, FlaskConical, Calculator, Brain } from 'lucide-react';

export type DataProvenance = 'MEASURED' | 'SIMULATED' | 'CALCULATED' | 'MODEL_PREDICTED';

const provenanceConfig: Record<DataProvenance, { 
  label: string; 
  variant: 'success' | 'warning' | 'info' | 'default';
  icon: typeof Database;
  description: string;
}> = {
  MEASURED: { 
    label: 'Measured', 
    variant: 'success', 
    icon: Database,
    description: 'Directly measured by physical sensor'
  },
  SIMULATED: { 
    label: 'Simulated', 
    variant: 'warning', 
    icon: FlaskConical,
    description: 'Generated by telemetry simulator'
  },
  CALCULATED: { 
    label: 'Calculated', 
    variant: 'info', 
    icon: Calculator,
    description: 'Derived from measured values via algorithm'
  },
  MODEL_PREDICTED: { 
    label: 'ML Predicted', 
    variant: 'default', 
    icon: Brain,
    description: 'Predicted by machine learning model'
  },
};

interface ProvenanceBadgeProps {
  provenance: DataProvenance;
  showDescription?: boolean;
  size?: 'sm' | 'md';
}

export function ProvenanceBadge({ 
  provenance, 
  showDescription = false,
  size = 'sm'
}: ProvenanceBadgeProps) {
  const config = provenanceConfig[provenance] || provenanceConfig.MEASURED;
  const Icon = config.icon;

  const sizeClasses = {
    sm: 'px-1.5 py-0.5 text-xs',
    md: 'px-2 py-1 text-sm',
  };

  const iconSize = size === 'sm' ? 'w-3 h-3' : 'w-4 h-4';

  if (!showDescription) {
    return (
      <span 
        className={cn(
          'inline-flex items-center gap-1 rounded-full font-medium',
          config.variant === 'success' && 'bg-success/10 text-success',
          config.variant === 'warning' && 'bg-warning/10 text-warning',
          config.variant === 'info' && 'bg-info/10 text-info',
          config.variant === 'default' && 'bg-text-muted/10 text-text-muted',
          sizeClasses[size]
        )}
        title={config.description}
      >
        <Icon className={iconSize} />
        {config.label}
      </span>
    );
  }

  return (
    <div className="flex items-center gap-2" title={config.description}>
      <span 
        className={cn(
          'inline-flex items-center gap-1 rounded-full font-medium',
          config.variant === 'success' && 'bg-success/10 text-success',
          config.variant === 'warning' && 'bg-warning/10 text-warning',
          config.variant === 'info' && 'bg-info/10 text-info',
          config.variant === 'default' && 'bg-text-muted/10 text-text-muted',
          sizeClasses[size]
        )}
      >
        <Icon className={iconSize} />
        {config.label}
      </span>
      <span className="text-caption text-text-muted">{config.description}</span>
    </div>
  );
}

export function ProvenanceLegend() {
  return (
    <div className="flex flex-wrap gap-3 text-sm">
      {(Object.entries(provenanceConfig) as [DataProvenance, typeof provenanceConfig[DataProvenance]][]).map(([key, config]) => (
        <span 
          key={key}
          className={cn(
            'inline-flex items-center gap-1.5 rounded-full px-2 py-1',
            config.variant === 'success' && 'bg-success/10 text-success',
            config.variant === 'warning' && 'bg-warning/10 text-warning',
            config.variant === 'info' && 'bg-info/10 text-info',
            config.variant === 'default' && 'bg-text-muted/10 text-text-muted',
          )}
        >
          <config.icon className="w-3 h-3" />
          <span>{config.label}</span>
        </span>
      ))}
    </div>
  );
}